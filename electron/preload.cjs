const { contextBridge, ipcRenderer } = require('electron');

contextBridge.exposeInMainWorld('bridgeux', Object.freeze({
  modelStatus: () => ipcRenderer.invoke('bridgeux:model-status'),
  browserBridge: () => ipcRenderer.invoke('bridgeux:browser-bridge'),
  routeAgentTask: request => ipcRenderer.invoke('bridgeux:agent-route', request),
  performBrowserMedia: request => ipcRenderer.invoke('bridgeux:browser-media', request),
  setAgentStatus: request => ipcRenderer.invoke('bridgeux:agent-status', request),
  onAgentStop: callback => ipcRenderer.on('bridgeux:agent-stop-request', callback),
  requestAgentStop: () => ipcRenderer.send('bridgeux:overlay-stop'),
  onAgentStatus: callback => ipcRenderer.on('bridgeux:agent-status', (_event, status) => callback(status)),
  askLocal: request => ipcRenderer.invoke('bridgeux:ask-local', request),
  listScreens: () => ipcRenderer.invoke('bridgeux:list-screens'),
  chooseScreen: id => ipcRenderer.invoke('bridgeux:choose-screen', id),
  captureScreen: id => ipcRenderer.invoke('bridgeux:capture-screen', id),
  inspectScreen: request => ipcRenderer.invoke('bridgeux:inspect-screen', request),
  getUiSnapshot: () => ipcRenderer.invoke('bridgeux:ui-snapshot'),
  analyzeUiScreen: request => ipcRenderer.invoke('bridgeux:analyze-ui', request),
  performUiAction: request => ipcRenderer.invoke('bridgeux:ui-action', request),
  searchWeb: request => ipcRenderer.invoke('bridgeux:web-search', request),
  openWebsite: url => ipcRenderer.invoke('bridgeux:open-website', url),
  getGestureAssets: () => ipcRenderer.invoke('bridgeux:gesture-assets'),
  setGestureMode: enabled => ipcRenderer.invoke('bridgeux:gesture-mode', enabled),
  movePointer: request => ipcRenderer.invoke('bridgeux:move-pointer', request),
  setAgentMode: enabled => ipcRenderer.invoke('bridgeux:agent-mode', enabled),
  planAgentStep: request => ipcRenderer.invoke('bridgeux:agent-step', request),
  performAgentAction: request => ipcRenderer.invoke('bridgeux:agent-action', request),
  translateSignVideo: request => ipcRenderer.invoke('bridgeux:translate-sign-video', request),
  performApprovedAction: action => ipcRenderer.invoke('bridgeux:perform-action', action),
  startSpeech: language => ipcRenderer.invoke('bridgeux:speech-start', language),
  stopSpeech: () => ipcRenderer.invoke('bridgeux:speech-stop'),
  pauseSpeech: () => ipcRenderer.invoke('bridgeux:speech-pause'),
  sendSpeechAudio: samples => ipcRenderer.send('bridgeux:speech-audio', samples),
  onSpeechResult: callback => ipcRenderer.on('bridgeux:speech-result', (_event, result) => callback(result)),
  speakText: request => ipcRenderer.invoke('bridgeux:speak-text', request),
  onTtsAudio: callback => ipcRenderer.on('bridgeux:tts-audio', (_event, audio) => callback(audio)),
}));
